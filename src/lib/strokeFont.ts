// Single-stroke ("engraving") vector font for pen-plotting text.
//
// Pen plotters cannot draw filled glyphs legibly — they draw lines. So instead
// of rasterising rendered text (which produced illegible horizontal-hatch
// blobs), we describe every character as a set of polyline strokes on a fixed
// design grid and emit them as real SVG <polyline> geometry. That feeds the
// normal vector pipeline (parseSvgPaths → generateGcode) and renders cleanly.
//
// Design grid (math coordinates, y points UP):
//   baseline   y = 0
//   x-height   y = 9
//   cap height y = 14
//   descender  y = -4   (for g j p q y , ; etc.)
// Each glyph is [advanceWidth, strokes] where a stroke is a list of [x, y]
// points. Curves are approximated by short polylines.

