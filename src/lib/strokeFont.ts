const FALLBACK: Glyph = [10, [[[1,0],[9,0],[9,14],[1,14],[1,0]]]]; // tofu box

function getFont(fontStyle: FontStyle): Record<string, Glyph> {
  switch (fontStyle) {
    case "round":  return ROUND_FONT;
    case "script": return { ...ROUND_FONT, ...SCRIPT_OVERRIDES };
    default:       return SANS_FONT;
  }
}

/** Measure one line's advance width in design units. */
function lineWidth(line: string, font: Record<string, Glyph>): number {
  let w = 0;
  for (const ch of line) {
    const g = font[ch] ?? FALLBACK;
    w += g[0] + LETTER_SPACING;
  }
  return Math.max(0, w - LETTER_SPACING);
}

/**
 * Render text as single-stroke SVG geometry (<polyline> elements). The result
 * has fill="none" stroke="black", so the normal vector slicer draws clean
 * letter strokes instead of raster fill. Multi-line text (\n) is supported.
 */
export function textToStrokeSvg(
  text: string,
  fontStyle: FontStyle = "sans",
): { svg: string; w: number; h: number } {
  const font = getFont(fontStyle);
  const isScript = fontStyle === "script";
  const shear = isScript ? SCRIPT_SHEAR : 0;

  const lines = text.split("\n");
  const maxWidth = Math.max(1, ...lines.map((l) => lineWidth(l, font)));
  // Extra horizontal space needed for the italic lean at cap height
  const shearExtra = shear * (CAP_HEIGHT - DESCENDER);
  const totalW = maxWidth + PAD * 2 + shearExtra;
  const totalH = (lines.length - 1) * LINE_ADVANCE + (CAP_HEIGHT - DESCENDER) + PAD * 2;

  const polylines: string[] = [];

  lines.forEach((line, lineIdx) => {
    let penX = PAD;
    const lineTop = PAD + lineIdx * LINE_ADVANCE;
    for (const ch of line) {
      const [adv, strokes] = font[ch] ?? FALLBACK;
      for (const stroke of strokes) {
        const pts = stroke
          .map(([x, y]) => {
            // y in design coords is y-up; SVG is y-down → flip relative to cap
            const sy = lineTop + (CAP_HEIGHT - y);
            // apply italic shear: bottom (y=0 design → sy=lineTop+CAP) stays,
            // top shifts right. In SVG coords y_design = CAP_HEIGHT - (sy - lineTop)
            const sx = penX + x + y * shear;
            return `${sx.toFixed(2)},${sy.toFixed(2)}`;
          })
          .join(" ");
        polylines.push(`  <polyline points="${pts}" fill="none" stroke="black" stroke-width="0.6"/>`);
      }
      penX += adv + LETTER_SPACING;
    }
  });

  const w = Math.ceil(totalW);
  const h = Math.ceil(totalH);
  const svg = [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">`,
    ...polylines,
    `</svg>`,
  ].join("\n");

  return { svg, w, h };
}
